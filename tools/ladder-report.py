#!/usr/bin/env python3
"""Generate the standings table of a multi-deck ladder as Markdown (single source for docs).

Usage:
  python3 tools/ladder-report.py <batchUuid> [--tiers docs/deck-pool/cota-tiers.json]
                                 [--out docs/deck-pool/cota-ladder.md]

Reads `.simulations/<uuid>/{ratings,batch}.json` (legacy-scale ratings are converted, see
ratings_io.py) and writes: header, standings (rank, deck, hand tier, Aember Score ± 95%
bootstrap, W-L, win%, SOS) and tier validation of the ladder against the hand tiers.
Nothing here is typed by hand — regenerate instead of editing the output.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ratings_io import ROOT, load_batch, load_names, load_ratings  # noqa: E402

TIER_LABELS = {6: "S+", 5: "S", 4: "A", 3: "B", 2: "C", 0: "Z"}


def rank_values(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    ranks, i = [0.0] * len(xs), 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for k in range(i, j + 1):
            ranks[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return ranks


def spearman(a, b):
    ra, rb = rank_values(a), rank_values(b)
    n = len(a)
    ma, mb = sum(ra) / n, sum(rb) / n
    num = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    den = (sum((x - ma) ** 2 for x in ra) * sum((y - mb) ** 2 for y in rb)) ** 0.5
    return num / den if den else float("nan")


def agreement(scores, tiers):
    total, agree = 0, 0.0
    for i in range(len(scores)):
        for j in range(i + 1, len(scores)):
            if tiers[i] == tiers[j]:
                continue
            total += 1
            p = (scores[i] - scores[j]) * (tiers[i] - tiers[j])
            agree += 1.0 if p > 0 else (0.5 if p == 0 else 0.0)
    return agree / total if total else float("nan")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("batch")
    ap.add_argument("--tiers", default=os.path.join(ROOT, "docs/deck-pool/cota-tiers.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "docs/deck-pool/cota-ladder.md"))
    args = ap.parse_args()

    import json
    ratings = sorted(load_ratings(args.batch), key=lambda r: -r["aemberScore"])
    names = load_names(args.batch)
    batch = load_batch(args.batch)
    tiers = json.load(open(args.tiers)) if os.path.exists(args.tiers) else {}
    total = sum(r["matches"] for r in ratings) // 2
    draws = sum(r["draws"] for r in ratings) // 2

    out = [
        "# CotA reference ladder — current standings",
        "",
        f"_Generated by `tools/ladder-report.py` from batch `{args.batch}` — do not edit by hand._",
        "",
        f"{len(ratings)} decks, round-robin, {total:,} matches, tactical AI, "
        f"{draws} draws. Aember Score = `50 + 12.5·ln(r/median)` (≈ 1 point per 2pp win-rate edge); "
        "± is the 95% stratified-bootstrap interval. `SOS` = strength of schedule. Hand tiers come from "
        "`cota-tiers.json`.",
        "",
        "| Rank | Deck | Tier | Aember Score | ±95% | W-L | Win% | SOS |",
        "|-----:|------|:----:|-------------:|:----:|:----|-----:|----:|",
    ]
    for i, r in enumerate(ratings, 1):
        tier = TIER_LABELS.get(int(tiers[r["deckUuid"]]), "") if r["deckUuid"] in tiers else ""
        lo, hi = r.get("aemberScoreLow"), r.get("aemberScoreHigh")
        half = f"±{(hi - lo) / 2:.1f}" if lo is not None and hi is not None else ""
        out.append(
            f"| {i} | {names.get(r['deckUuid'], r['deckName'])} | {tier} | {r['aemberScore']:.1f} | {half} | "
            f"{r['wins']}-{r['losses']} | {r['winRate'] * 100:.1f} | {r['sos']:.3f} |"
        )
    low = [r for r in ratings if r["lowConfidence"]]
    out += ["", "\\* low confidence (< 20 games): " + (", ".join(r["deckName"] for r in low) if low else "none"), ""]

    labelled = [r for r in ratings if r["deckUuid"] in tiers]
    if len(labelled) >= 3:
        s = [r["aemberScore"] for r in labelled]
        t = [tiers[r["deckUuid"]] for r in labelled]
        out += [
            f"## Tier validation ({len(labelled)} labelled decks)",
            "",
            f"Spearman **{spearman(s, t):.2f}**, pairwise agreement **{agreement(s, t) * 100:.1f}%** "
            "(also available live via `POST /api/mass-simulations/{uuid}/tier-validation`).",
            "",
            "Compare two ladders with `python3 tools/ladder-compare.py <old> <new> --tiers docs/deck-pool/cota-tiers.json`.",
            "",
        ]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    open(args.out, "w").write("\n".join(out))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    sys.exit(main())
